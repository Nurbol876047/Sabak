  "title": "Название отчета",
  "intro": "Вводная часть текста",
  "sections": [
    {
      "sectionTitle": "Название раздела",
      "content": "Текст раздела"
    }
  ],
  "recommendations": "Рекомендации/задачи на следующий период"
