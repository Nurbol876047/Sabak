import { callAI, parseAIJson } from './aiClient';

export async function generateScenario(input, options = {}) {
  const prompt = `Сен — тәжірибелі әдіскер және педагогсың.
Тақырыбы: ${input.topic}
Сынып/Жасы: ${input.age}
Оқушылар саны: ${input.studentsCount || 'Көрсетілмеген'}
Ұзақтығы: ${input.duration || '45'} минут
Сынып ерекшеліктері: ${input.features || 'Жоқ'}

Көрсетілген оқушылар жасына және ұзақтығына дәл сәйкес келетін тәрбие сағатының толық сценарийін қазақ тілінде жаз.
ТЕК JSON форматында жауап бер, ешқандай түсініктемесіз және markdown \`\`\`json блоктарынсыз.
JSON алдында немесе соңында ешқандай мәтін қоспа. Барлық мәтінді қазақ тілінде жаз.

JSON форматы:
{
  "intro": "Мұғалімнің кіріспе сөзі (мәтін)",
  "main_parts": [
    {
      "title": "Кезең атауы",
      "duration": "Х минут",
      "teacher_action": "Мұғалім не істейді/айтады",
      "student_action": "Оқушылар не істейді"
    }
  ],
  "conclusion": "Қорытынды сөз және рефлексия (мәтін)"
}`;

  const response = await callAI(prompt, { ...options, requireJSON: true });
  return parseAIJson(response.text);
}

